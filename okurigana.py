def needs_okurigana(ch, reading):
    """その漢字をその読みで読むには、送り仮名が要るか。"""
    if not ch or not reading:
        return False
    return reading in NEEDS_OKURIGANA.get(ch, ())


def without_okurigana(ch, readings):
    """
    **送り仮名が付いていないとき**に使ってよい読みだけを返す。

    全部落ちてしまうときは、**元のまま返す**。読みがゼロになると
    その塊は「読めない」ことになり、直せるはずのものまで
    土俵に上がれなくなる（項目48-AI で懲りた形）。
    """
    if not readings:
        return readings
    kept = [r for r in readings if not needs_okurigana(ch, r)]
    return kept if kept else list(readings)


def stats():
    """表の大きさ（診断用）。"""
    return {'kanji': len(NEEDS_OKURIGANA),
            'readings': sum(len(v) for v in NEEDS_OKURIGANA.values())}
