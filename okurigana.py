"""
**送り仮名が付いて初めて成立する読み**の表。

うにさんの指定（2026-08-11）:

「音読みを優先するよりも、**送り仮名があるかを先にチェック**して
みましょう。**あやまがくしゅう**の例は把握していますか？
**誤り、誤る、誤って** など、後ろの平仮名が付いていることで
**あやま**と読めます。**送り仮名がなければ、ご と読む**ことが
分かります」

これは順位づけではなく、**構造の決まり**である。

    誤学習   誤 の後ろは 学（漢字）＝送り仮名が無い
             → **あやま とは読めない**。ご しかない
             → ごがくしゅう。IMEに打っても 誤学習 が出る

    待ち外   待 の後ろは ち（平仮名）＝送り仮名がある
             → **まち と読んでよい**（湯桶読みでも通る）

**音読み・訓読みの印（kanji_onkun）では、ここは裁けなかった**
（項目48-AI）。`待ち外` が まち(訓)＋がい(音) の湯桶読みなので、
「音読みを先に」では説明が付かず、印を門にすると壊れる。
**送り仮名の有無なら、湯桶読みも重箱読みも正しく通る。**

表の作り方（`okurigana_build.py`）:

  1. IPAdic の見出し語のうち、**漢字1字＋ひらがな**で、
     品詞が**動詞・形容詞**のものを集める
     （誤る・誤って・学ぶ・習う・待つ・正しい …）
  2. 読みから送り仮名ぶんを引くと、**漢字の読み（語幹）**が残る
     （あやまる − る ＝ **あやま**）
  3. ただし、その読みで**単独でも見出しになっている**もの
     （外＝そと・業＝わざ・間＝ま）と、
     `kanji_onkun` が持っている読みは**外す**。
     単独で立つ読みは、送り仮名が無くても使えるため。

使い方:

    needs_okurigana('誤', 'あやま')  → True   （送り仮名が要る）
    needs_okurigana('誤', 'ご')      → False
    without_okurigana('誤', ['ご', 'あやま'])  → ['ご']

**空にはしない。** 全部落ちるときは元のまま返す
（読めない塊にすると、直せるはずのものまで届かなくなる）。
"""

