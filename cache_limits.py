"""
補正の控え（functools.lru_cache）の上限をここ1か所で決める（2026-10-24・うにさん「控えを小さく」）。

解析の子は同じ子のまま何度も解析するので、控えが満杯まで育つ（上限の合計 約106万件・1件 約330バイト）。
各モジュールは `lru_cache(maxsize=_cache_size(4096))` のように元の上限を渡し、ここで係数を掛ける。
控えは答えを変えない（同じ引数に同じ答えを返す関数だけに付いている）。小さくして変わるのは、もう一度
計算する回数だけ。打ってすぐの行は直前に使った控えに当たるので、上限を下げても残る。
"""

SCALE = 0.25      # 元の上限に掛ける係数
SMALL = 1024      # これより小さい上限（1・128 など）はそのまま
FLOOR = 512       # 掛けた後の下限


def size(n):
    if n is None or n < SMALL:
        return n
    return max(FLOOR, int(n * SCALE))
