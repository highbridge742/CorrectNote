# 形容詞の活用語尾。原形の末尾「い」を置き換える形で作る。
ADJ_ENDINGS = ['い', 'く', 'かった', 'くない', 'ければ', 'さ']


def expand_adjective(reading, surface):
    """
    形容詞の原形から活用形を作る。

    「はやい/速い」→ はやく/速く, はやかった/速かった ...
    全活用形を辞書に列挙する代わりに、語尾の差分だけを扱う。
    """
    if not reading.endswith('い') or not surface.endswith('い'):
        return []
    stem_r = reading[:-1]
    stem_s = surface[:-1]
    out = []
    for ending in ADJ_ENDINGS:
        if ending == 'い':
            continue
        out.append((stem_r + ending, stem_s + ending))
    return out


SEED_VOCABULARY = SEED_VOCABULARY + BASE_FORMS


def load_seed(store):
    """
    語彙ストアに初期語彙を投入する。既存の語には触れない。

    形容詞は原形だけを登録しておき、活用形はここで自動的に作る。
    （辞書に全活用形を書き並べる必要がない）
    """
    added = 0

    def _add(reading, surface, category):
        nonlocal added
        existing = [e for e in store.lookup(reading) if e['surface'] == surface]
        if existing:
            return
        store.add(reading, surface, category)
        # 初期語彙はユーザーが意図した語なので、
        # 辞書から取り込んだだけの語（count=1）と区別するためにcountを2にする
        entry = store._by_reading[reading].get(surface)
        if entry:
            entry['count'] = 2
        added += 1

    for reading, surface, category in SEED_VOCABULARY:
        _add(reading, surface, category)
        # 形容詞なら活用形も一緒に入れておく
        for r2, s2 in expand_adjective(reading, surface):
            _add(r2, s2, category)

    return added
