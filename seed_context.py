# 「connect」のような紛れ込みを弾くための簡単な検査。
# 日本語（ひらがな・カタカナ・漢字）を含まない語は話題に入れない。


def _is_japanese(word):
    for ch in word:
        if ('\u3041' <= ch <= '\u3096'      # ひらがな
                or '\u30a1' <= ch <= '\u30fa'   # カタカナ
                or '\u4e00' <= ch <= '\u9fff'   # 漢字
                or ch == 'ー'):
            return True
    return False


def load_seed_topics(context_vec):
    """
    初期の話題のまとまりを、文脈ベクトルに読み込ませる。

    「同じ行に一緒に書かれた語」として観測させるだけなので、
    context_vec 側に専用の仕組みは要らない。
    まとまりが大きいと共起の窓（CO_WINDOW）から外れる語が出るため、
    窓の幅ずつ位置をずらしながら、まとまり全体が互いに
    結び付くように複数回観測させる。

    戻り値: 読み込んだ話題の数
    """
    if context_vec is None:
        return 0
    from context_vec import CO_WINDOW

    n = 0
    for topic in SEED_TOPICS:
        words = [w for w in topic if _is_japanese(w)]
        if len(words) < 2:
            continue
        # まとまりの中の語が全て互いに近いことを表したいが、
        # observe_line は「近い語ほど強く結び付ける」ため、
        # 一度並べただけでは端と端が結び付かない。
        # 並びをずらしながら複数回観測させて、まとまり全体を
        # 均等に結び付ける。
        step = max(1, CO_WINDOW)
        for offset in range(0, len(words), step):
            rotated = words[offset:] + words[:offset]
            context_vec.observe_line(rotated)
        n += 1
    return n
