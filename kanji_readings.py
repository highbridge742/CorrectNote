KANJI_READINGS = {k: v for k, v in KANJI_READINGS.items()
                  if v and all('\u3041' <= c <= '\u3096' or c == 'ー'
                               for r in v for c in r)}


def readings_of(ch):
    """この漢字の読みの候補（よく使う順）。無ければ空リスト。"""
    return list(KANJI_READINGS.get(ch, ()))


def has(ch):
    return ch in KANJI_READINGS


# 日常の文章でまず使わない漢字。
#
# 「魔訶」の「訶」のように、目にした瞬間「なんだこの文字は」と
# なる漢字がある。こういう漢字が混ざった短い塊は、
# 2文字であっても誤変換とみなしてよい
# （実機での指摘：「魔訶は読めとはいえ存在してるだけで
#   なんだこの文字はとなる。それほど異様な文字列」）。
#
# 逆に「見切」のように、日常的な漢字だけでできた2文字は、
# 正しい語の一部である可能性が高いので触ってはいけない
# （「見切れます」を「右れます」に壊した実例がある）。
#
# ここに挙げるのは「読めるが日常では使わない」漢字。
# 固有名詞・仏教語・古語・当て字に出てくるものが中心で、
# IMEが妙な変換をしたときにだけ現れる。
