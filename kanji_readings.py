def is_everyday(ch):
    """
    その漢字が、日常の文章に出てくるものか。

    日常的でない漢字が混ざっているなら、その塊は
    短くても誤変換を疑ってよい、という判断に使う。
    """
    if ch in RARE_KANJI:
        return False
    # 自前の表に載っている漢字は、日常語として選んで入れたもの。
    if ch in KANJI_READINGS:
        return True
    # 表にも稀用一覧にも無い漢字は、判断がつかない。
    # 安全側（日常的である＝触らない）に倒す。
    return True
